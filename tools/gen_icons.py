"""Generate Android vector drawables from the Hugeicons Flutter package data.

Usage: python gen_icons.py <stroke_rounded.dart> <out_drawable_dir> <out_kotlin_file> name1 name2 ...
Names are Hugeicons identifiers without the 'strokeRounded' prefix, e.g. Restaurant01.
Writes res/drawable/hi_<snake>.xml and a Kotlin object mapping names to R.drawable ids.
"""
import re
import sys

src_path, out_dir, kt_path, *names = sys.argv[1:]
src = open(src_path, encoding='utf-8').read()


def block(name):
    m = re.search(r'static const List<List<dynamic>> strokeRounded%s = \[(.*?)\n  \];' % re.escape(name), src, re.S)
    return m.group(1) if m else None


def elements(body):
    for m in re.finditer(r"\[\s*'(\w+)',\s*\{(.*?)\}\s*\]", body, re.S):
        attrs = dict(re.findall(r"'(\w+)':\s*'([^']*)'", m.group(2), re.S))
        yield m.group(1), attrs


def f(v):
    return float(v)


def to_path(tag, a):
    if tag == 'path':
        return a['d']
    if tag == 'circle':
        cx, cy, r = f(a['cx']), f(a['cy']), f(a['r'])
        return f"M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0Z"
    if tag == 'ellipse':
        cx, cy, rx, ry = f(a['cx']), f(a['cy']), f(a['rx']), f(a['ry'])
        return f"M{cx - rx},{cy}a{rx},{ry} 0 1,0 {2 * rx},0a{rx},{ry} 0 1,0 {-2 * rx},0Z"
    if tag == 'line':
        return f"M{a['x1']},{a['y1']}L{a['x2']},{a['y2']}"
    if tag == 'rect':
        x, y, w, h = f(a.get('x', 0)), f(a.get('y', 0)), f(a['width']), f(a['height'])
        rx = f(a.get('rx', a.get('ry', 0)))
        ry = f(a.get('ry', a.get('rx', 0)))
        if rx == 0:
            return f"M{x},{y}h{w}v{h}h{-w}Z"
        return (f"M{x + rx},{y}h{w - 2 * rx}a{rx},{ry} 0 0,1 {rx},{ry}v{h - 2 * ry}"
                f"a{rx},{ry} 0 0,1 {-rx},{ry}h{-(w - 2 * rx)}a{rx},{ry} 0 0,1 {-rx},{-ry}"
                f"v{-(h - 2 * ry)}a{rx},{ry} 0 0,1 {rx},{-ry}Z")
    raise ValueError(f'unsupported element {tag}')


def snake(name):
    s = re.sub(r'(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Z])', '_', name).lower()
    return 'hi_' + s


missing, written = [], []
for name in names:
    body = block(name)
    if body is None:
        missing.append(name)
        continue
    paths = []
    for tag, a in elements(body):
        attrs = [f'android:pathData="{to_path(tag, a)}"']
        if a.get('fill') not in (None, 'none'):
            attrs.append('android:fillColor="#FF000000"')
        if a.get('stroke') not in (None, 'none'):
            attrs += [
                'android:strokeColor="#FF000000"',
                f'android:strokeWidth="{a.get("strokeWidth", "1.5")}"',
                f'android:strokeLineCap="{a.get("strokeLinecap", "round")}"',
                f'android:strokeLineJoin="{a.get("strokeLinejoin", "round")}"',
            ]
        if 'opacity' in a:
            attrs += [f'android:fillAlpha="{a["opacity"]}"', f'android:strokeAlpha="{a["opacity"]}"']
        paths.append('    <path ' + '\n        '.join(attrs) + ' />')
    res = snake(name)
    with open(f'{out_dir}/{res}.xml', 'w', encoding='utf-8', newline='\n') as out:
        out.write('<!-- Generated from Hugeicons (MIT); see assets/licenses/Hugeicons-MIT.txt -->\n')
        out.write('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                  '    android:width="24dp" android:height="24dp"\n'
                  '    android:viewportWidth="24" android:viewportHeight="24">\n')
        out.write('\n'.join(paths) + '\n</vector>\n')
    written.append((name, res))

with open(kt_path, 'w', encoding='utf-8', newline='\n') as kt:
    kt.write('package app.geocent.ui.theme\n\nimport app.geocent.R\n\n')
    kt.write('/** Hugeicons stroke-rounded drawables, generated by tools/gen_icons.py from the hugeicons Flutter package. Do not edit. */\n')
    kt.write('object HugeIcons {\n')
    for name, res in written:
        kt.write(f'    val {name[0].lower() + name[1:]} = R.drawable.{res}\n')
    kt.write('}\n')

print(f'wrote {len(written)} icons')
if missing:
    print('MISSING:', ' '.join(missing))
